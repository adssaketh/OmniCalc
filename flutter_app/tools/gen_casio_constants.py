#!/usr/bin/env python3
"""Writes lib/engine/casio/casio_constants_data.dart: the 40 scientific constants of the fx-991ES PLUS (manual p.52-53),
CODATA 2014 values. Values come from scipy's bundled CODATA 2014 table (an independent source), except entry 09 (h/2pi,
computed) and entry 38 (t = 273.15, a definition). Run: python3 tools/gen_casio_constants.py [--check]."""
import math, sys, os
from scipy.constants import _codata as cd

D = cd._physical_constants_2014
ROWS = [  # (no, symbol shown, manual name, scipy key, unit)
 (1,'mp','proton mass','proton mass','kg'),
 (2,'mn','neutron mass','neutron mass','kg'),
 (3,'me','electron mass','electron mass','kg'),
 (4,'mμ','muon mass','muon mass','kg'),
 (5,'a0','Bohr radius','Bohr radius','m'),
 (6,'h','Planck constant','Planck constant','J s'),
 (7,'μN','nuclear magneton','nuclear magneton','J/T'),
 (8,'μB','Bohr magneton','Bohr magneton','J/T'),
 (9,'ħ','Planck constant, rationalized',None,'J s'),
 (10,'α','fine-structure constant','fine-structure constant',''),
 (11,'re','classical electron radius','classical electron radius','m'),
 (12,'λC','Compton wavelength','Compton wavelength','m'),
 (13,'γp','proton gyromagnetic ratio','proton gyromag. ratio','1/(s T)'),
 (14,'λCp','proton Compton wavelength','proton Compton wavelength','m'),
 (15,'λCn','neutron Compton wavelength','neutron Compton wavelength','m'),
 (16,'R∞','Rydberg constant','Rydberg constant','1/m'),
 (17,'u','atomic mass unit','atomic mass constant','kg'),
 (18,'μp','proton magnetic moment','proton mag. mom.','J/T'),
 (19,'μe','electron magnetic moment','electron mag. mom.','J/T'),
 (20,'μn','neutron magnetic moment','neutron mag. mom.','J/T'),
 (21,'μμ','muon magnetic moment','muon mag. mom.','J/T'),
 (22,'F','Faraday constant','Faraday constant','C/mol'),
 (23,'e','elementary charge','elementary charge','C'),
 (24,'NA','Avogadro constant','Avogadro constant','1/mol'),
 (25,'k','Boltzmann constant','Boltzmann constant','J/K'),
 (26,'Vm','molar volume of ideal gas (273.15 K, 100 kPa)','molar volume of ideal gas (273.15 K, 100 kPa)','m^3/mol'),
 (27,'R','molar gas constant','molar gas constant','J/(mol K)'),
 (28,'C0','speed of light in vacuum','speed of light in vacuum','m/s'),
 (29,'C1','first radiation constant','first radiation constant','W m^2'),
 (30,'C2','second radiation constant','second radiation constant','m K'),
 (31,'σ','Stefan-Boltzmann constant','Stefan-Boltzmann constant','W/(m^2 K^4)'),
 (32,'ε0','electric constant','electric constant','F/m'),
 (33,'μ0','magnetic constant','mag. constant','N/A^2'),
 (34,'Φ0','magnetic flux quantum','mag. flux quantum','Wb'),
 (35,'g','standard acceleration of gravity','standard acceleration of gravity','m/s^2'),
 (36,'G0','conductance quantum','conductance quantum','S'),
 (37,'Z0','characteristic impedance of vacuum','characteristic impedance of vacuum','ohm'),
 (38,'t','Celsius temperature',None,'K'),
 (39,'G','Newtonian constant of gravitation','Newtonian constant of gravitation','m^3/(kg s^2)'),
 (40,'atm','standard atmosphere','standard atmosphere','Pa'),
]
def value(no, key):
    if no == 9: return D['Planck constant'][0] / (2*math.pi)
    if no == 38: return 273.15
    return D[key][0]
def lit(v): return repr(float(v))
out = ['// GENERATED by tools/gen_casio_constants.py. Do not edit.',
       '// The 40 scientific constants of the fx-991ES PLUS (CONST, manual p.52-53), CODATA 2014 recommended values.','',
       'class CasioConstant {','  const CasioConstant(this.no, this.symbol, this.name, this.value, this.unit);',
       '  final int no;','  final String symbol;','  final String name;','  final double value;','  final String unit;','}','',
       'const List<CasioConstant> kCasioConstants = <CasioConstant>[']
for no, sym, name, key, unit in ROWS:
    out.append("  CasioConstant(%d, '%s', '%s', %s, '%s')," % (no, sym, name, lit(value(no, key)), unit))
out.append('];'); out.append('')
text = '\n'.join(out)
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'lib', 'engine', 'casio', 'casio_constants_data.dart')
if '--check' in sys.argv:
    cur = open(path, encoding='utf-8').read()
    sys.exit(0 if cur == text else 1)
open(path, 'w', encoding='utf-8').write(text)
print('wrote', path)
