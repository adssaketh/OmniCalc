#!/usr/bin/env python3
"""Turns test/casio/intended_differences.raw.json (written by legacy_diff_test.dart with UPDATE_CASIO_DIFF=1) into
test/casio/intended_differences.json (ids and manual citations added) and docs/INTENDED_DIFFERENCES.md."""
import json, pathlib, re, sys

root = pathlib.Path(__file__).resolve().parent.parent
raw = json.load(open(root / 'test/casio/intended_differences.raw.json'))

CATS = {
    'D-ERR-1': ('Error wording', 'The unit shows its own messages: Math ERROR, Syntax ERROR, Argument ERROR (manual p.92-95). The legacy messages ("Division by zero", "Domain error ...") are no longer shown.', 'p.92-95'),
    'D-PRI-1': ('Negative sign below powers', '−2^2 is −(2^2) = −4: powers and postfix functions have a higher priority than the negative sign (priority table, manual p.96, with its note on squaring negative values).', 'p.96'),
    'D-PRI-2': ('Powers and postfix functions go left to right', '2^3^2, 5^2^0 and 2^3! are evaluated left to right because they share priority 3 (manual p.96: "when the priority of two expressions is the same, the calculation is performed from left to right"). UNVERIFIED on a real unit (real_device.json).', 'p.96'),
    'D-RANGE-1': ('Results beyond 9.999999999×10^99', 'The calculation range is ±1×10^-99 to ±9.999999999×10^99 (manual p.97) and factorial is limited to 0..69 (p.99): larger results are Math ERROR, not Infinity.', 'p.97, p.99'),
    'D-DOM-1': ('Input-range checks', 'Domain rows of "Function Calculation Input Ranges and Precision": 0^0, 0^-1 and negative bases with a non-integer exponent have no result (manual p.99-100).', 'p.99-100'),
    'D-ROOT-1': ('Cube roots and odd roots', '³√x is the cube root (manual p.38 Example 6) and odd roots of negative numbers exist: ∛(−27) = −3, (−8)^(1/3) = −2 (power/root domain, p.99-100).', 'p.38, p.99-100'),
    'D-SYN-1': ('Syntax is strict', 'Input the unit would reject is a Syntax ERROR: a second decimal point, two numbers side by side, unknown words, a lowercase x, a comma outside a function (manual p.19, p.93-94).', 'p.19, p.93-94'),
    'D-NUM-1': ('A leading decimal point', '.5+.5 is 0.5+0.5 = 1. The legacy engine read ".5" wrongly.', 'p.17-18'),
    'D-MUL-1': ('Implicit multiplication', '2c and 2e multiply (omitted × sign, priority 7, manual p.96), so a constant after a number is no longer ignored or rejected.', 'p.96'),
    'D-PAREN-1': ('Closing parenthesis at the end', 'A closing parenthesis may be omitted at the very end of the input: (1+2 is 3 (manual p.19 and the FAQ on p.102).', 'p.19, p.102'),
    'D-ARG-1': ('Integer-only functions', 'GCD and LCM take integers (manual p.46-47); anything else is an Argument ERROR.', 'p.46-47'),
}

def classify(d):
    e, old, new = d['expr'], str(d['old']), str(d['new'])
    if old.startswith('ERROR ') and new.startswith('ERROR '):
        return 'D-ERR-1'
    if e in ('−2^2',):
        return 'D-PRI-1'
    if e in ('2^3^2', '5^2^0', '2^3!'):
        return 'D-PRI-2'
    if e in ('2^1023', '2^1024', '170!', '171!'):
        return 'D-RANGE-1'
    if e in ('0^0', '0^−1', '(−1)!', '2.5!'):
        return 'D-DOM-1'
    if e.startswith('³√') or e in ('root(3,−8)', '(−8)^(1/3)'):
        return 'D-ROOT-1'
    if e in ('.5+.5',):
        return 'D-NUM-1'
    if e in ('2c', '2e'):
        return 'D-MUL-1'
    if e == '(1+2':
        return 'D-PAREN-1'
    if e.startswith('gcd(') or e.startswith('lcm('):
        return 'D-ARG-1'
    if 'ERROR' in new:
        return 'D-SYN-1'
    sys.exit('unclassified difference: %r' % d)

out = []
for d in raw:
    cid = classify(d)
    out.append({**d, 'id': cid, 'manual': CATS[cid][2]})
json.dump(out, open(root / 'test/casio/intended_differences.json', 'w'), ensure_ascii=False, indent=1)

lines = ['# Intended differences between the Casio engine and the legacy OmniCalc engine', '',
         'Generated by `tools/gen_casio_diff_doc.py` from the diff of every Part 6 evaluator vector (`test/golden/evaluator.json`).',
         '`test/casio/legacy_diff_test.dart` fails when a difference is not listed here, so nothing changes silently.',
         'Every input below gives a different result in "Calculation style: Casio" than in "OmniCalc (legacy)".',
         'The legacy style keeps the old result for all of them.', '',
         '## Results that look different but are not in the vectors', '',
         '- **Exact forms (D-EXACT-1):** `√2×√3` shows `√6`, `1/3+1/2` shows `5⌟6`, `π÷6` shows `π÷6` (manual p.21-22). The number inside is the same as the old decimal, `S⇔D` shows the decimal.',
         '- **Rounding at the 10th digit (D-ROUND-1):** results show 10 significant digits (the legacy formatter showed 12), calculation uses 15 (manual p.97).',
         '- **Percent:** unchanged. "Percent style: OmniCalc" is the default; `100+10%` = 110.', '']
by = {}
for d in out:
    by.setdefault(d['id'], []).append(d)
for cid in sorted(by):
    title, why, cite = CATS[cid]
    lines += ['## %s %s' % (cid, title), '', why, '', '| Input | Angle | Old result | New result | Manual |', '|---|---|---|---|---|']
    for d in by[cid]:
        lines.append('| `%s` | %s | %s | %s | %s |' % (d['expr'].replace('|', '\\|'), d['mode'], str(d['old']).replace('|', '\\|'), str(d['new']).replace('|', '\\|'), cite))
    lines.append('')
(root.parent / 'docs').mkdir(exist_ok=True)
open(root.parent / 'docs/INTENDED_DIFFERENCES.md', 'w').write('\n'.join(lines))
print(len(out), 'differences listed')
